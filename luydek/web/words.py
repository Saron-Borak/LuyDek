def lang() -> str:
    return LANG.get()


def use(code: str | None) -> str:
    """Set the language for this request (a page render); unknown codes fall back to English."""
    code = code if code in LANGS else "en"
    LANG.set(code)
    return code


def say(text: str, **kw) -> str:
    """`text` in the request's language, with {placeholders} filled in. The English plural follows `n`,
    or `count` when the number that decides it is another one ("{n} left, about {d} days", count=d)."""
    n = kw.pop("count", kw.get("n"))
    if LANG.get() == "km" and text in KM:
        out = KM[text]
    else:
        one, _, many = text.partition("|")
        out = many if many and n != 1 else one
    return out.format(**kw) if kw else out


def unit(word: str | None) -> str:
    if not word:
        return ""
    return UNITS_KM.get(word.lower(), word) if LANG.get() == "km" else word


def date(text: str) -> str:
    """A date written by clock.day_words / when_words, in Khmer when the page is: "5 Oct" -> "5 តុលា"."""
    if LANG.get() != "km" or not text:
        return text
    for en, km in zip(MONTHS_EN, MONTHS_KM, strict=True):
        text = text.replace(en, km)
    return text.replace("today", "ថ្ងៃនេះ").replace("Today", "ថ្ងៃនេះ").replace("yesterday", "ម្សិលមិញ") \
        .replace("Yesterday", "ម្សិលមិញ")


def weekday(d) -> str:
    """The day of the week, in the page's language: "Friday" / "ថ្ងៃសុក្រ"."""
    return f"ថ្ងៃ{DAYS_KM[d.weekday()]}" if LANG.get() == "km" else d.strftime("%A")


def weekday_short(d) -> str:
    return DAYS_KM[d.weekday()] if LANG.get() == "km" else d.strftime("%a")


def missing(templates_text: str) -> list[str]:
    """Phrases a template wraps with _() that have no Khmer yet (for the check list)."""
    import re
    found = re.findall(r"""_\(\s*(["'])(.+?)\1""", templates_text)
    return sorted({t for _, t in found if t not in KM})


